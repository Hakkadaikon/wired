#!/usr/bin/env python3
"""Convert BoringSSL FileTest vector files into C arrays for the test build.

Usage: scripts/gen_bssl_vectors.py tests/vectors/boringssl/<file>.txt [...]
Writes tests/vectors/boringssl/<stem>.h next to each input. The values are
kept as the vector file's raw text (hex, or a "quoted" string); the test-side
helpers in tests/vectors/boringssl/bssl_vec.h decode them. Nothing here
computes an expected value: every expectation comes from the vector file.

FileTest format: "KEY = value" or "KEY: value" is an attribute, "[k = v]" is
an instruction that applies to every following case, "#" starts a comment,
and a blank line ends a case.
"""

import os
import re
import sys

ATTR = re.compile(r"^([A-Za-z0-9_.-]+)\s*(?:=|:)\s*(.*)$")
INSTR = re.compile(r"^\[\s*([A-Za-z0-9_.-]+)\s*(?:=|:)?\s*(.*?)\s*\]$")


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _flush(st, last):
    if st["cur"]:
        st["cases"].append((st["first"], last, list(st["instr"].items()) + st["cur"]))
        st["cur"] = []


def _blank(st, no, raw, m):
    _flush(st, no - 1)


def _comment(st, no, raw, m):
    pass


def _instr(st, no, raw, m):
    st["instr"]["[" + m.group(1)] = m.group(2)


def _attr(st, no, raw, m):
    if not st["cur"]:
        st["first"] = no
    st["cur"].append((m.group(1), m.group(2).strip()))


def _unparsed(st, no, raw, m):
    raise SystemExit(f"{st['path']}:{no}: unparsed line: {raw!r}")


# first matching pattern decides how a stripped line is handled
LINE_KINDS = [
    (re.compile(r"^$"), _blank),
    (re.compile(r"^#"), _comment),
    (INSTR, _instr),
    (ATTR, _attr),
    (re.compile(""), _unparsed),
]


def _kind(line):
    for p, fn in LINE_KINDS:
        m = p.match(line)
        if m:
            return fn, m


def _line(st, no, raw):
    fn, m = _kind(raw.strip())
    fn(st, no, raw, m)


def parse(path):
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    st = {"path": path, "cases": [], "cur": [], "first": 0, "instr": {}}
    for no, raw in enumerate(lines, 1):
        _line(st, no, raw)
    _flush(st, len(lines))
    return st["cases"]


def _write(f, path, stem, attrs, rows):
    f.write("/* clang-format off */\n")
    f.write(
        f"/* Generated by scripts/gen_bssl_vectors.py from\n"
        f" * {os.path.basename(path)}. Do not edit. */\n"
    )
    f.write(f"static const bssl_attr bssl_{stem}_attrs[] = {{\n")
    f.writelines(f"  {{{c_str(k)}, {c_str(v)}}},\n" for k, v in attrs)
    f.write("};\n")
    f.write(f"static const bssl_case bssl_{stem}_cases[] = {{\n")
    f.writelines(
        f"  {{{first}, {last}, {off}, {n}}},\n" for first, last, off, n in rows
    )
    f.write("};\n/* clang-format on */\n")


def emit(path):
    stem = re.sub(r"\W", "_", os.path.splitext(os.path.basename(path))[0])
    cases = parse(path)
    out = os.path.join(os.path.dirname(path), stem + ".h")
    attrs, rows = [], []
    for first, last, kv in cases:
        rows.append((first, last, len(attrs), len(kv)))
        attrs.extend(kv)
    with open(out, "w", encoding="utf-8") as f:
        _write(f, path, stem, attrs, rows)
    print(f"{out}: {len(cases)} cases")


if __name__ == "__main__":
    for p in sys.argv[1:]:
        emit(p)
