#!/usr/bin/env python3
"""Split tests/run.c into K shard TUs for parallel compilation.

tests/run.c stays the single source of truth (its include list and main()
calls); this script only regroups them. The single-TU `just test` remains
the commit gate -- shards cannot detect cross-TU static/typedef/macro
collisions, so `test-fast` is a fast dev-loop approximation only.

Tests call static functions of their production .c directly, so each
production file and its *_test.c MUST land in the same shard TU. The
mapping lives in shard_groups.py.
"""

import os
import re
import sys
from itertools import chain

from shard_groups import K, plan

RUN_C = "tests/run.c"
OUT_DIR = "build/shards"

GENERATED = "/* generated by scripts/gen_shards.py -- do not edit */"
INCLUDE = re.compile(r'#include "(.+\.c)"')
CALL = re.compile(r"\s*(test_\w+)\(\);")


def _include(line, prod, tests):
    m = INCLUDE.match(line)
    if m:
        (tests if m.group(1).endswith("_test.c") else prod).append(m.group(1))


def _call(line, calls):
    m = CALL.match(line)
    if m:
        calls.append(m.group(1))


def parse_run_c():
    prod, tests, calls = [], [], []
    for line in open(RUN_C):
        _include(line, prod, tests)
        _call(line, calls)
    return prod, tests, calls


def test_functions(test):
    """Entry functions defined in a test file (static ones included: the
    shard entry lives in the same TU, exactly like run.c's main)."""
    src = open(os.path.join("tests", test)).read()
    return re.findall(r"^(?:static )?void (test_\w+)\(void\)", src, re.M)


def write_if_changed(path, content):
    if os.path.exists(path) and open(path).read() == content:
        return
    with open(path, "w") as f:
        f.write(content)


def check_unique(prod, tests):
    for lst, what in ((prod, "production"), (tests, "test")):
        if len(set(lst)) != len(lst):
            sys.exit("gen_shards: duplicate %s include in run.c" % what)


def _headers_in(d, fs):
    return [os.path.relpath(os.path.join(d, f), "src") for f in fs if f.endswith(".h")]


def all_headers():
    """every shard sees every production header: in the unity TU all
    production .c precede all tests, so tests freely use cross-domain
    public declarations; the headers restore that visibility per shard."""
    return sorted(
        chain.from_iterable(_headers_in(d, fs) for d, _, fs in os.walk("src"))
    )


def shard_prod(ctx, s):
    return chain.from_iterable(
        ctx["groups"].prod_of(ctx["merged"], r) for r in s["roots"]
    )


def shard_files(ctx, s):
    sprod = sorted(shard_prod(ctx, s), key=ctx["prod_order"].get)
    stests = sorted(
        chain.from_iterable(ctx["gtests"][r] for r in s["roots"]),
        key=ctx["test_order"].get,
    )
    return sprod, stests


def _claim(ctx, fn, t, fns):
    if fn not in ctx["call_order"]:
        return  # helper called from another test_*, not main
    if fn in ctx["fn_of"]:
        sys.exit("gen_shards: %s defined in %s and %s" % (fn, ctx["fn_of"][fn], t))
    ctx["fn_of"][fn] = t
    fns.append(fn)


def shard_fns(ctx, stests):
    fns = []
    for t in stests:
        for fn in test_functions(t):
            _claim(ctx, fn, t, fns)
    fns.sort(key=lambda f: ctx["call_order"].get(f, -1))
    return fns


def _section_includes(files):
    # each .c in its own .text section: see build/unity/run.c in
    # gen_ninja.sh (assembler branch padding vs section size)
    lines = []
    for k, f in enumerate(files):
        lines += ['#pragma clang section text=".text.u%d"' % k, '#include "%s"' % f]
    return lines


def render_shard(n, headers, files, fns):
    return (
        "\n".join(
            [GENERATED, '#include "test.h"']
            + ['#include "%s"' % h for h in headers]
            + _section_includes(files)
            + ["int wired_test_shard_%d(void) {" % n]
            + ["  %s();" % fn for fn in fns]
            + ["  return wired_test_fails;", "}"]
        )
        + "\n"
    )


def emit_shard(ctx, n, s):
    sprod, stests = shard_files(ctx, s)
    fns = shard_fns(ctx, stests)
    ctx["emitted"].extend(fns)
    content = render_shard(n, ctx["headers"], sprod + stests, fns)
    write_if_changed(os.path.join(OUT_DIR, "shard_%d.c" % n), content)


def check_calls(fn_of, calls):
    """invariant: run.c's main() calls are covered, nothing extra"""
    if sorted(fn_of) == sorted(calls):
        return
    sys.exit(
        "gen_shards: test call mismatch vs run.c main: shards=%d run.c=%d "
        "(missing: %s extra: %s)"
        % (
            len(fn_of),
            len(calls),
            sorted(set(calls) - set(fn_of)),
            sorted(set(fn_of) - set(calls)),
        )
    )


def check_covered(ctx, prod):
    covered = list(chain.from_iterable(shard_prod(ctx, s) for s in ctx["shards"]))
    if sorted(covered) != sorted(prod):
        sys.exit("gen_shards: production include set differs from run.c")


def render_main():
    return (
        "\n".join(
            [GENERATED, "#include <stdio.h>"]
            + ["int wired_test_shard_%d(void);" % n for n in range(K)]
            + ["int main(void) {", "  int fails = 0;"]
            + ["  fails += wired_test_shard_%d();" % n for n in range(K)]
            + [
                '  if (fails) { printf("%d failure(s)\\n", fails); return 1; }',
                '  printf("all tests passed\\n");',
                "  return 0;",
                "}",
            ]
        )
        + "\n"
    )


def order(lst):
    return {x: i for i, x in enumerate(lst)}


def main():
    prod, tests, calls = parse_run_c()
    check_unique(prod, tests)
    ctx = plan(prod, tests)
    ctx.update(
        prod_order=order(prod),
        test_order=order(tests),
        call_order=order(calls),
        fn_of={},
        emitted=[],
        headers=all_headers(),
    )
    os.makedirs(OUT_DIR, exist_ok=True)
    for n, s in enumerate(ctx["shards"]):
        emit_shard(ctx, n, s)
    check_calls(ctx["fn_of"], calls)
    check_covered(ctx, prod)
    write_if_changed(os.path.join(OUT_DIR, "shard_main.c"), render_main())
    print(
        "gen_shards: %d shards, %d prod, %d tests, %d calls"
        % (K, len(prod), len(tests), len(ctx["emitted"]))
    )


if __name__ == "__main__":
    main()
