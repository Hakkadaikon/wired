static int pmt_parse(wired_span tbs) {
  x509_policy_maps m;
  return x509_policy_mappings(tbs, &m);
}

/* RFC 5280 4.2.1.5: no extension is "absent" (0), not an error. */
static void test_pm_absent(void) {
  x509             c;
  x509_policy_maps m;
  CHECK(x509_parse(PMT_SPAN(pol_good_ca_der), &c) == 1);
  CHECK(x509_policy_mappings(c.tbs, &m) == 0);
  CHECK(m.n == 0);
}

/* One pair is read with both sides viewed in order. */
static void test_pm_one_pair(void) {
  x509_policy_maps m;
  CHECK(x509_policy_mappings(PMT_SPAN(pmt_one), &m) == 1);
  CHECK(m.n == 1);
  CHECK(der_oid_equal(m.idp[0], PMT_SPAN(pmt_p1)) == 1);
  CHECK(der_oid_equal(m.sdp[0], PMT_SPAN(pmt_p2)) == 1);
}

/* Two pairs sharing an issuerDomainPolicy are both kept. */
static void test_pm_two_pairs(void) {
  x509_policy_maps m;
  CHECK(x509_policy_mappings(PMT_SPAN(pmt_two), &m) == 1);
  CHECK(m.n == 2);
  CHECK(der_oid_equal(m.sdp[1], PMT_SPAN(pmt_p1)) == 1);
}

/* RFC 5280 4.2.1.5 SIZE (1..MAX): an empty SEQUENCE is malformed. */
static void test_pm_empty_rejects(void) {
  CHECK(pmt_parse(PMT_SPAN(pmt_empty)) == -1);
}

/* RFC 5280 4.2.1.5 / 6.1.4 (a): anyPolicy on either side is rejected. */
static void test_pm_any_policy_rejects(void) {
  CHECK(pmt_parse(PMT_SPAN(pmt_any_issuer)) == -1);
  CHECK(pmt_parse(PMT_SPAN(pmt_any_subject)) == -1);
}

/* A pair is exactly two OIDs; a third element, a non-OID, or bytes after
 * the outer SEQUENCE are malformed. */
static void test_pm_malformed_rejects(void) {
  CHECK(pmt_parse(PMT_SPAN(pmt_three_oids)) == -1);
  CHECK(pmt_parse(PMT_SPAN(pmt_not_oid)) == -1);
  CHECK(pmt_parse(PMT_SPAN(pmt_trailing)) == -1);
}

/* X509_POLICY_MAPS_MAX (16) pairs fit (ovf1 carries exactly 16). A 17th
 * is valid DER: it is kept out (truncated) rather than called malformed,
 * and a graph handed such a certificate is marked overflowed. */
static void test_pm_cap(void) {
  x509              c;
  x509_policy_maps  m;
  x509_policy_graph g;
  CHECK(x509_parse(PMT_SPAN(pol_ovf1_der), &c) == 1);
  CHECK(x509_policy_mappings(c.tbs, &m) == 1);
  CHECK(m.n == X509_POLICY_MAPS_MAX);
  CHECK(m.truncated == 0);
  CHECK(x509_policy_mappings(PMT_SPAN(pmt_cap17), &m) == 1);
  CHECK(m.n == X509_POLICY_MAPS_MAX);
  CHECK(m.truncated == 1);
  x509_policy_graph_init(&g);
  CHECK(x509_policy_graph_map(&g, PMT_SPAN(pmt_cap17), 1) == 1);
  CHECK(g.overflow == 1);
}

/* RFC 5280 4.2: a critical policyMappings that cannot be processed is an
 * unprocessed critical extension; a well-formed critical one, a malformed
 * non-critical one and an absent one are not. */
static void test_pm_unprocessed_critical(void) {
  CHECK(x509_pm_unprocessed_critical(PMT_SPAN(pmt_crit_empty)) == 1);
  CHECK(x509_pm_unprocessed_critical(PMT_SPAN(pmt_crit_ok)) == 0);
  CHECK(x509_pm_unprocessed_critical(PMT_SPAN(pmt_empty)) == 0);
  CHECK(x509_pm_unprocessed_critical(PMT_SPAN(pmt_one)) == 0);
  CHECK(x509_pm_unprocessed_critical(PMT_SPAN(pmt_cap17)) == 0);
}

void test_policymap(void) {
  test_pm_absent();
  test_pm_one_pair();
  test_pm_two_pairs();
  test_pm_empty_rejects();
  test_pm_any_policy_rejects();
  test_pm_malformed_rejects();
  test_pm_cap();
  test_pm_unprocessed_critical();
}
