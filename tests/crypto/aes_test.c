static int bytes16_differ(const u8 a[16], const u8 b[16]);

static int aesb_eq(const u8* a, const u8* b) { return !bytes16_differ(a, b); }

/* The round key words rk[4r..4r+3] as the 16 state bytes they XOR in. */
static void aesb_rk_bytes(const u32* rk, u8 out[16]) {
  for (usz c = 0; c < 4; c++) {
    out[4 * c]     = (u8)(rk[c] >> 24);
    out[4 * c + 1] = (u8)(rk[c] >> 16);
    out[4 * c + 2] = (u8)(rk[c] >> 8);
    out[4 * c + 3] = (u8)rk[c];
  }
}

/* FIPS 197 Appendix B: drive the round steps one at a time and compare the
 * state after each SubBytes, ShiftRows (5.1.2), MixColumns and
 * AddRoundKey with the published per-round values. */
static void test_aes_appendix_b_rounds(void) {
  static const u8 in[16] = {0x32, 0x43, 0xf6, 0xa8, 0x88, 0x5a, 0x30, 0x8d,
                            0x31, 0x31, 0x98, 0xa2, 0xe0, 0x37, 0x07, 0x34};
  u8              key[16], s[16], k[16];
  aes128          a;
  hb("2b7e151628aed2a6abf7158809cf4f3c", key);
  aes128_init(&a, key);
  for (usz r = 0; r <= AES_ROUNDS; r++) {
    aesb_rk_bytes(a.rk + 4 * r, k);
    CHECK(aesb_eq(k, aesb_rk[r]));
  }
  aes128_copy16(s, in);
  add_round_key(s, a.rk);
  for (usz r = 0; r < AES_ROUNDS; r++) {
    CHECK(aesb_eq(s, aesb_start[r]));
    sub_bytes(s);
    CHECK(aesb_eq(s, aesb_sub[r]));
    shift_rows(s);
    CHECK(aesb_eq(s, aesb_shift[r]));
    if (r + 1 < AES_ROUNDS) {
      mix_columns(s);
      CHECK(aesb_eq(s, aesb_mix[r]));
    }
    add_round_key(s, a.rk + 4 * (r + 1));
  }
  hb("3925841d02dc09fbdc118597196a0b32", k);
  CHECK(aesb_eq(s, k));
}

/* FIPS 197 4.2.1: {57} times {02}, {04}, ... {80} by repeated XTIMES, and
 * {57} * {13} = {57} ^ {ae} ^ {07} = {fe} (4.2: addition is XOR). */
static void test_aes_xtimes(void) {
  static const u8 want[8] = {0x57, 0xae, 0x47, 0x8e, 0x07, 0x0e, 0x1c, 0x38};
  u8              v       = 0x57;
  for (usz i = 0; i < 8; i++) {
    CHECK(v == want[i]);
    v = XTIME(v);
  }
  CHECK((u8)(0x57 ^ XTIME(0x57) ^ XTIME(XTIME(XTIME(XTIME(0x57))))) == 0xfe);
}

static int bytes16_differ(const u8 a[16], const u8 b[16]) {
  int differs = 0;
  for (usz i = 0; i < 16; i++) {
    differs |= (a[i] != b[i]);
  }
  return differs;
}

/* FIPS 197 6.2: the implementation shall impose no restriction on an
 * appropriately generated key beyond its length. aes128_init has no
 * key-validation branch (aes.c schedules every byte unconditionally), so
 * degenerate 16-byte keys (all-zero, all-0xff) that a "weak key" check
 * might reject are accepted and encrypt without error. */
static void test_aes_no_key_restriction_beyond_length(void) {
  u8     zero_key[16] = {0}, ff_key[16], in[16] = {0}, out_zero[16], out_ff[16];
  aes128 a_zero, a_ff;
  for (usz i = 0; i < 16; i++) {
    ff_key[i] = 0xff;
  }

  aes128_init(&a_zero, zero_key);
  aes128_encrypt(&a_zero, in, out_zero);
  aes128_init(&a_ff, ff_key);
  aes128_encrypt(&a_ff, in, out_ff);

  /* Both degenerate keys produced *some* ciphertext (no crash/rejection),
   * and distinct keys still yield distinct ciphertext for the same
   * plaintext, i.e. the key was actually used rather than short-circuited
   * by a validation check. */
  CHECK(bytes16_differ(out_zero, out_ff));
}

/* aes256_hb32 parses a 64-char hex string into 32 bytes. */
static void aes256_hb32(const char* hex, u8 out[32]) {
  for (usz i = 0; i < 32; i++) {
    u8 hi = hex[i * 2], lo = hex[i * 2 + 1];
    out[i] = (u8)(((hi <= '9' ? hi - '0' : hi - 'a' + 10) << 4) |
                  (lo <= '9' ? lo - '0' : lo - 'a' + 10));
  }
}

/* FIPS 197 Appendix C.3: AES-256 known-answer test. Recomputed
 * independently with Python's cryptography library (AES256-ECB) before
 * being baked in here; it matches the value below. */
static void test_aes256_appendix_c3(void) {
  u8     key[32], in[16], out[16], want[16];
  aes256 a;
  aes256_hb32(
      "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f", key);
  hb("00112233445566778899aabbccddeeff", in);
  hb("8ea2b7ca516745bfeafc49904b496089", want);
  aes256_init(&a, key);
  aes256_encrypt(&a, in, out);
  for (usz i = 0; i < 16; i++) {
    CHECK(out[i] == want[i]);
  }
}

/* FIPS 197 6.2: no restriction on an appropriately generated key beyond its
 * length; degenerate 256-bit keys still produce distinct ciphertext. */
static void test_aes256_no_key_restriction_beyond_length(void) {
  u8     zero_key[32] = {0}, ff_key[32], in[16] = {0}, out_zero[16], out_ff[16];
  aes256 a_zero, a_ff;
  for (usz i = 0; i < 32; i++) {
    ff_key[i] = 0xff;
  }

  aes256_init(&a_zero, zero_key);
  aes256_encrypt(&a_zero, in, out_zero);
  aes256_init(&a_ff, ff_key);
  aes256_encrypt(&a_ff, in, out_ff);

  CHECK(bytes16_differ(out_zero, out_ff));
}

