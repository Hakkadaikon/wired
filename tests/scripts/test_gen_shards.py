"""Tests for scripts/gen_shards.py (run: python3 -m unittest discover tests/scripts)."""
import importlib.util
import io
import os
import pathlib
import re
import sys
import tempfile
import unittest
from contextlib import redirect_stdout

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import shard_groups  # noqa: E402


def load_module():
    spec = importlib.util.spec_from_file_location("gen_shards", ROOT / "scripts" / "gen_shards.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class PureTest(unittest.TestCase):
    def setUp(self):
        self.g = load_module()

    def test_parse_run_c(self):
        with tempfile.TemporaryDirectory() as d:
            p = pathlib.Path(d, "run.c")
            p.write_text('#include "test.h"\n#include "a/b.c"\n#include "b_test.c"\n'
                         'int main(void) {\n  test_b();\n  other();\n}\n')
            self.g.RUN_C = str(p)
            self.assertEqual(self.g.parse_run_c(), (["a/b.c"], ["b_test.c"], ["test_b"]))

    def test_match_tiers(self):
        groups = shard_groups.Groups(["x/conn/foo.c", "conn/y.c", "a/conn/z/w.c", "q/r.c"])
        self.assertEqual(groups.match("foo"), ["x/conn"])  # file beats dir/component
        self.assertEqual(groups.match("conn"), ["x/conn", "conn"])  # dir name beats a/conn/z
        self.assertEqual(groups.match("z"), ["a/conn/z"])
        self.assertEqual(sorted(shard_groups.Groups(["a/conn/z/w.c", "b/conn/v/u.c"]).match("conn")),
                         ["a/conn/z", "b/conn/v"])  # component tier
        self.assertEqual(groups.match("nope"), [])

    def test_resolve_strips_suffixes_and_unions(self):
        groups = shard_groups.Groups(["d/foo.c", "e/foo.c", "f/bar.c"])
        root = shard_groups.resolve(groups, "x/foo_extra_more_test.c")
        self.assertEqual(groups.find("d"), groups.find("e"))
        self.assertEqual(root, groups.find("d"))
        self.assertEqual(shard_groups.resolve(groups, "bar_test.c"), "f")

    def test_resolve_override(self):
        groups = shard_groups.Groups(["crypto/symmetric/aead/gcm/gcm.c"])
        self.assertEqual(shard_groups.resolve(groups, "gcm256_test.c"), "crypto/symmetric/aead/gcm")

    def test_resolve_unresolved_exits(self):
        groups = shard_groups.Groups(["d/foo.c"])
        for t in ("zzz_test.c", "_foo_test.c", "_test.c"):
            with self.assertRaises(SystemExit) as cm:
                shard_groups.resolve(groups, t)
            self.assertIn("UNRESOLVED test " + t, str(cm.exception))

    def test_write_if_changed(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "f")
            self.g.write_if_changed(p, "a")
            os.utime(p, (0, 0))
            self.g.write_if_changed(p, "a")
            self.assertEqual(os.stat(p).st_mtime, 0)
            self.g.write_if_changed(p, "b")
            self.assertEqual(pathlib.Path(p).read_text(), "b")


class RealTreeTest(unittest.TestCase):
    """Shards the real tests/run.c into a temp dir and checks the result covers
    run.c exactly: every production include, every test file and every main()
    call lands in exactly one shard."""

    @classmethod
    def setUpClass(cls):
        g = load_module()
        cls.tmp = tempfile.TemporaryDirectory()
        g.OUT_DIR = cls.tmp.name
        old = os.getcwd()
        os.chdir(ROOT)
        try:
            out = io.StringIO()
            with redirect_stdout(out):
                g.main()
            cls.prod, cls.tests, cls.calls = g.parse_run_c()
        finally:
            os.chdir(old)
        cls.out = out.getvalue()
        cls.k = g.K
        cls.shards = [pathlib.Path(cls.tmp.name, "shard_%d.c" % n).read_text() for n in range(g.K)]
        cls.main_c = pathlib.Path(cls.tmp.name, "shard_main.c").read_text()

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_summary_line(self):
        self.assertEqual(self.out, "gen_shards: %d shards, %d prod, %d tests, %d calls\n"
                         % (self.k, len(self.prod), len(self.tests), len(self.calls)))

    def test_every_c_include_exactly_once(self):
        got = [f for s in self.shards for f in re.findall(r'#include "(.+\.c)"', s)]
        self.assertEqual(sorted(got), sorted(self.prod + self.tests))

    def test_every_call_exactly_once(self):
        got = [c for s in self.shards for c in re.findall(r"^  (test_\w+)\(\);$", s, re.M)]
        self.assertEqual(sorted(got), sorted(self.calls))

    def test_shard_layout(self):
        for n, s in enumerate(self.shards):
            lines = s.splitlines()
            self.assertEqual(lines[:2], ["/* generated by scripts/gen_shards.py -- do not edit */",
                                         '#include "test.h"'])
            self.assertIn("int wired_test_shard_%d(void) {" % n, lines)
            self.assertEqual(lines[-2:], ["  return wired_test_fails;", "}"])

    def test_main_c(self):
        for n in range(self.k):
            self.assertIn("  fails += wired_test_shard_%d();\n" % n, self.main_c)
        self.assertTrue(self.main_c.endswith('  printf("all tests passed\\n");\n  return 0;\n}\n'))


if __name__ == "__main__":
    unittest.main()
