/* The capture's server-chosen SCID the client switched its DCID onto. */
static const u8 neqo_srv_scid[6] = {0x12, 0xa3, 0x01, 0x9c, 0x34, 0xb2};

/* Mutable copies: opening removes header protection in place. */
static u8 pnshort_head[sizeof(neqo_ch_head_dg)];
static u8 pnshort_tail[sizeof(neqo_ch_tail_dg)];

static wired_mspan pnshort_copy(u8* dst, const u8* src, usz n) {
  for (usz i = 0; i < n; i++) dst[i] = src[i];
  return wired_mspan_of(dst, n);
}

/* Feed the real head fragment (pn 727, two-byte encoding), ack it, admit
 * the switched DCID, then feed the real tail fragment (pn 731, ONE-byte
 * encoding): the accumulator must absorb it and complete the ClientHello. */
static void test_srvboot_absorbs_short_pn_retransmit(void) {
  wired_srvboot_acc a;
  u8                ack[288];
  wired_srvboot_acc_reset(&a);
  CHECK(wired_srvboot_acc_feed(
      &a,
      pnshort_copy(pnshort_head, neqo_ch_head_dg, sizeof(neqo_ch_head_dg))));
  CHECK(a.largest_pn == 727);
  CHECK(!wired_srvboot_acc_complete(&a));
  CHECK(
      wired_srvboot_partial_ack(
          &a, wired_span_of(neqo_srv_scid, 6), ack, sizeof(ack)) > 0);
  wired_srvboot_acc_allow(&a, wired_span_of(neqo_srv_scid, 6));
  CHECK(wired_srvboot_acc_feed(
      &a,
      pnshort_copy(pnshort_tail, neqo_ch_tail_dg, sizeof(neqo_ch_tail_dg))));
  CHECK(a.largest_pn == 731);
  CHECK(wired_srvboot_acc_complete(&a));
}

void test_srvboot_pnshort(void) { test_srvboot_absorbs_short_pn_retransmit(); }
